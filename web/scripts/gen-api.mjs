// Regenerate src/api/schema.d.ts from the FastAPI OpenAPI spec (no running server needed).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'

const root = resolve(import.meta.dirname, '..', '..')
const candidates = [
  process.env.RAPTOR_PYTHON,
  resolve(root, '.venv/Scripts/python.exe'),
  resolve(root, '.venv/bin/python'),
  'python',
].filter(Boolean)
const python = candidates.find((p) => p === 'python' || existsSync(p))
const spec = execFileSync(
  python,
  ['-c', 'import json; from raptor.server.app import create_app; print(json.dumps(create_app().openapi()))'],
  { cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
)
const ast = await openapiTS(JSON.parse(spec))
mkdirSync(resolve(import.meta.dirname, '../src/api'), { recursive: true })
const header = '/* Generated by `npm run gen:api` from the FastAPI OpenAPI schema. Do not edit. */\n\n'
writeFileSync(resolve(import.meta.dirname, '../src/api/schema.d.ts'), header + astToString(ast))
console.log('wrote src/api/schema.d.ts')
