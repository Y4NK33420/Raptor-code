"""Find the source files of a repository.

Respects ``.gitignore`` (via ``git ls-files`` when the repo is a git checkout, else by
reading every ``.gitignore`` with :mod:`pathspec`), and skips binary, vendored and
generated files.
"""

from __future__ import annotations

import hashlib
import logging
import os
import shutil
import subprocess
from collections.abc import Iterable
from pathlib import Path

from .config import IngestConfig

logger = logging.getLogger(__name__)

#: Directory names that hold vendored, generated or environment files.
SKIP_DIRS = frozenset(
    {
        ".git",
        ".hg",
        ".svn",
        "__pycache__",
        "node_modules",
        "bower_components",
        "vendor",
        "vendored",
        "_vendor",
        "third_party",
        "thirdparty",
        "site-packages",
        "dist",
        "build",
        ".tox",
        ".nox",
        ".eggs",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
        ".venv",
        "venv",
        "env",
        ".env",
        ".idea",
        ".vscode",
        ".cache",
    }
)
GENERATED_SUFFIXES = ("_pb2.py", "_pb2_grpc.py", "_pb2.pyi", ".min.js", ".min.css", ".g.py")
GENERATED_MARKERS = (
    "generated by",
    "do not edit",
    "autogenerated",
    "auto-generated",
    "@generated",
)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def is_binary(data: bytes) -> bool:
    return b"\x00" in data[:8192]


def is_generated(path: str, data: bytes) -> bool:
    if path.endswith(GENERATED_SUFFIXES):
        return True
    head = data[:600].decode("utf-8", errors="ignore").lower()
    return any(m in head for m in GENERATED_MARKERS)


def _skip_by_dir(rel: str) -> bool:
    parts = rel.split("/")[:-1]
    return any(p in SKIP_DIRS or p.endswith(".egg-info") for p in parts)


def _pathspec(patterns: Iterable[str]):
    import pathspec

    try:  # pathspec >= 0.12.2 names the git-compatible flavour "gitignore"
        return pathspec.PathSpec.from_lines("gitignore", list(patterns))
    except (KeyError, LookupError):
        return pathspec.PathSpec.from_lines("gitwildmatch", list(patterns))


def _git_files(root: Path) -> list[str] | None:
    git = shutil.which("git")
    if git is None or not (root / ".git").exists():
        return None
    try:
        out = subprocess.run(
            [git, "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True,
            check=True,
            timeout=60,
        ).stdout
    except (subprocess.SubprocessError, OSError) as exc:
        logger.warning("git ls-files failed (%s); falling back to walking the tree", exc)
        return None
    return sorted({p for p in out.decode("utf-8", errors="replace").split("\0") if p})


def _walk_files(root: Path) -> list[str]:
    """Walk ``root`` honouring every ``.gitignore`` found on the way down."""
    specs: list[tuple[str, object]] = []
    out: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        if ".gitignore" in filenames:
            lines = (Path(dirpath) / ".gitignore").read_text(encoding="utf-8", errors="ignore")
            specs.append((rel_dir, _pathspec(lines.splitlines())))

        def ignored(rel: str, is_dir: bool) -> bool:
            for base, spec in specs:
                if base and not rel.startswith(base + "/"):
                    continue
                sub = rel[len(base) + 1 :] if base else rel
                if spec.match_file(sub + ("/" if is_dir else "")):  # type: ignore[attr-defined]
                    return True
            return False

        keep = []
        for d in sorted(dirnames):
            rel = f"{rel_dir}/{d}" if rel_dir else d
            if d in SKIP_DIRS or d.endswith(".egg-info") or ignored(rel, True):
                continue
            keep.append(d)
        dirnames[:] = keep
        for f in sorted(filenames):
            rel = f"{rel_dir}/{f}" if rel_dir else f
            if not ignored(rel, False):
                out.append(rel)
    return sorted(out)


def discover_files(root: str | Path, cfg: IngestConfig, extensions: Iterable[str]) -> list[str]:
    """Relative POSIX paths of the indexable source files under ``root``."""
    root = Path(root)
    exts = tuple(e.lower() for e in extensions)
    candidates = (_git_files(root) if cfg.use_git else None) or _walk_files(root)
    exclude = _pathspec(cfg.exclude) if cfg.exclude else None
    include = _pathspec(cfg.include) if cfg.include else None
    out = []
    for rel in candidates:
        if not rel.lower().endswith(exts) or _skip_by_dir(rel) or rel.endswith(GENERATED_SUFFIXES):
            continue
        if exclude is not None and exclude.match_file(rel):
            continue
        if include is not None and not include.match_file(rel):
            continue
        out.append(rel)
    return out


def read_source(root: str | Path, rel: str, cfg: IngestConfig) -> bytes | None:
    """File contents, or ``None`` if the file is missing, too big, binary or generated."""
    path = Path(root) / rel
    try:
        if path.stat().st_size > cfg.max_file_bytes:
            logger.info("skipping %s: larger than %d bytes", rel, cfg.max_file_bytes)
            return None
        data = path.read_bytes()
    except OSError:
        return None
    if is_binary(data) or is_generated(rel, data):
        return None
    return data


def git_head(root: str | Path) -> str | None:
    git = shutil.which("git")
    if git is None or not (Path(root) / ".git").exists():
        return None
    try:
        out = subprocess.run(
            [git, "-C", str(root), "rev-parse", "HEAD"], capture_output=True, check=True, timeout=30
        ).stdout
    except (subprocess.SubprocessError, OSError):
        return None
    return out.decode().strip() or None


def git_changed_files(root: str | Path, since: str) -> set[str] | None:
    """Files changed since commit ``since`` (committed, staged, unstaged or untracked).

    Returns ``None`` when git is unavailable, so the caller falls back to hashing.
    """
    git = shutil.which("git")
    if git is None or not (Path(root) / ".git").exists():
        return None
    changed: set[str] = set()
    try:
        diff = subprocess.run(
            [git, "-C", str(root), "diff", "--name-only", "-z", since],
            capture_output=True,
            check=True,
            timeout=60,
        ).stdout
        others = subprocess.run(
            [git, "-C", str(root), "ls-files", "-z", "--others", "--exclude-standard"],
            capture_output=True,
            check=True,
            timeout=60,
        ).stdout
    except (subprocess.SubprocessError, OSError):
        return None
    for blob in (diff, others):
        changed.update(p for p in blob.decode("utf-8", errors="replace").split("\0") if p)
    return changed
